// Offline-Funktion der Toolbox.
// Bei jeder inhaltlichen Änderung der Toolbox die Versionsnummer erhöhen,
// damit Nutzer die neue Fassung bekommen.
const CACHE = 'toolbox-v1';
const FILES = [
  './',
  './index.html',
  './manifest.webmanifest',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/maskable-512.png',
  './icons/apple-touch-icon.png',
  '../assets/fonts/Inter-Regular.woff',
  '../assets/fonts/Inter-Medium.woff',
  '../assets/fonts/Inter-SemiBold.woff'
];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Seiten: erst online laden (immer aktuell), offline aus dem Speicher.
// Andere Dateien: aus dem Speicher, sonst online.
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req)
        .then(res => { const copy = res.clone(); caches.open(CACHE).then(c => c.put('./index.html', copy)); return res; })
        .catch(() => caches.match('./index.html'))
    );
    return;
  }
  e.respondWith(caches.match(req).then(hit => hit || fetch(req)));
});
